#!/usr/bin/env python3
"""Derive the grid filler's default floors, per entry length, from published answers.

tools/grid_fill.py refuses a word whose clueability or familiarity
(tools/clueability.py) is below a floor. Both scores fall with length: a
published 13-letter answer has a median clueability of 34 against 64 for a
4-letter one. So one floor for every length rejects most of what setters print
at the long end. Each length gets its own pair instead, set at QUANTILE of the
published answers of that length:

  clue         the QUANTILE point of clueability over published answers
  familiarity  the QUANTILE point of familiarity over the same answers

A published answer is a single-word solution (enumeration one number) in any
tracked puzzle except our own, counted once per appearance, so the floors
follow what solvers are actually shown. Answers the clueability cache does not
score cannot vote. A length with fewer than MIN_ANSWERS takes no floor of its
own; grid_fill.py uses the nearest length that has one.

    python3 tools/build_fill_floors.py           # rewrite tools/data/fill_floors.json
    python3 tools/build_fill_floors.py --check   # exit 1 if the committed file is stale

The nightly (tools/daily_update.sh) reruns it, since every fetched puzzle adds
answers and every scorer change moves the scores.
"""

import argparse
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clueability
from puzzle_paths import puzzle_files

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tools" / "data" / "fill_floors.json"

# At p25 about 60% of published answers clear both floors at every length
# (the axes correlate), against 5-45% under the old flat 40/25.
QUANTILE = 0.25
MIN_ANSWERS = 200


def quantile(xs, q):
    xs = sorted(xs)
    return xs[int(q * (len(xs) - 1))]


def derive():
    table = clueability.scores()
    if not table:
        raise SystemExit("no clueability cache and no lexicon to build one: run tools/fetch_lexicon.sh")
    scored = collections.defaultdict(list)  # length -> [(clue, familiarity)]
    for path in puzzle_files():
        p = json.loads(Path(path).read_text())
        if p.get("series") == "authored":
            continue
        for e in p.get("entries") or []:
            s = (e.get("solution") or "").upper()
            enum = ((e.get("clue") or {}).get("enumeration") or "").strip()
            if not (s.isalpha() and re.fullmatch(r"\d+", enum) and int(enum) == len(s)):
                continue
            if s in table:
                scored[len(s)].append(table[s][:2])
    floors = {}
    for length in sorted(scored):
        rows = scored[length]
        if len(rows) < MIN_ANSWERS:
            continue
        clue = quantile([c for c, _ in rows], QUANTILE)
        fam = quantile([f for _, f in rows], QUANTILE)
        floors[str(length)] = {
            "clue": clue,
            "familiarity": fam,
            "answers": len(rows),
            "answersPassing": round(sum(c >= clue and f >= fam for c, f in rows) / len(rows), 3),
        }
    return {
        "_about": "Generated by tools/build_fill_floors.py from published answers; do not edit.",
        "quantile": QUANTILE,
        "floors": floors,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if tools/data/fill_floors.json differs from a fresh derivation")
    args = ap.parse_args()
    new = derive()
    text = json.dumps(new, indent=1) + "\n"
    if args.check:
        old = OUT.read_text() if OUT.exists() else ""
        if old != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/build_fill_floors.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(
        f"{L}:{f['clue']}/{f['familiarity']}" for L, f in new["floors"].items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
