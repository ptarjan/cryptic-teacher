#!/usr/bin/env python3
"""Derive the joint vocabularies the authoring checks use from published clues.

tools/validate_annotations.py holds three rules about how a clue's pieces
attach (STYLE.md, "the joints"). Each needs a word list, and each list is a
claim about what published setters do, so each is measured here instead of
typed:

  linkWords   words published clues use as link words, beyond the equals-sign
              core the validator states itself (CORE_LINKS). A word qualifies
              when LINK_MIN_USES annotated clues by LINK_MIN_SETTERS different
              setters declare it. The same vocabulary is what may stand between
              an anagram indicator and its fodder.
  horizontal  reversal-indicator words bound to across entries: seen in at
  vertical    least AXIS_MIN reversal clues, at most AXIS_MAX_CROSS of them on
              the other axis. A word bound to neither axis is neutral.

    python3 tools/build_clue_joints.py           # rewrite tools/data/clue_joints.json
    python3 tools/build_clue_joints.py --check   # CI: fail if the file is stale

Only published puzzles count: our own clues cannot vote for our own rules.
"""

import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from puzzle_paths import puzzle_files

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tools" / "data" / "clue_joints.json"

# Set where the qualifying words are still joinery (then, but, seen, using,
# needing) and the July rejects (lives, mistake, spent, would) stay out;
# at 5 uses by 3 setters `would` gets in.
LINK_MIN_USES = 10
LINK_MIN_SETTERS = 5
# `back` sits on down entries in 14% of its reversal clues and `returning` in
# 23%, so neither binds; `up` crosses in 3 of 571 and `west` in 0 of 47.
AXIS_MIN = 10
AXIS_MAX_CROSS = 0.05


def derive():
    import validate_annotations as va  # its own tokeniser and readers, so counts match its checks
    link_uses = collections.Counter()
    link_setters = collections.defaultdict(set)
    reversal_indicators = []  # (words, direction)
    for path in puzzle_files():
        p = json.loads(Path(path).read_text())
        if p.get("series") == "authored":
            continue
        for e in p.get("entries") or []:
            a = e.get("annotation")
            if not a:
                continue
            for lw in a.get("linkWords") or []:
                for t in set(va.words_of(lw)):
                    link_uses[t] += 1
                    link_setters[t].add(p.get("setter"))
            if "reversal" in va.types_of(a) or va.assembly(a).get("reversals"):
                for ind in a.get("indicators") or []:
                    if ind.get("for") != "reversal":
                        continue  # an untyped indicator may be the clue's positional one
                    reversal_indicators.append((set(va.words_of(ind.get("text"))), e["direction"]))
    links = sorted(t for t, n in link_uses.items()
                   if n >= LINK_MIN_USES and len(link_setters[t]) >= LINK_MIN_SETTERS
                   and t not in va.CORE_LINKS)

    # Two passes, so a word is not bound for its company: single-word indicators
    # bind first (`up`), then multi-word ones that hold none of those words
    # (`going west`), which keeps `picked` and `served` from riding on `up`.
    def tally(indicators):
        axis = collections.defaultdict(collections.Counter)
        for ws, direction in indicators:
            for t in ws:
                axis[t][direction] += 1
        return axis

    def bound(axis, own, other):
        return {t for t, c in axis.items()
                if c[own] + c[other] >= AXIS_MIN
                and c[other] <= AXIS_MAX_CROSS * (c[own] + c[other])}

    single = tally([i for i in reversal_indicators if len(i[0]) == 1])
    first = bound(single, "across", "down") | bound(single, "down", "across")
    axis = tally([i for i in reversal_indicators if len(i[0]) == 1 or not i[0] & first])
    return {
        "_about": "Generated by tools/build_clue_joints.py from published annotations; do not edit.",
        "linkWords": {t: link_uses[t] for t in links},
        "horizontal": {t: dict(axis[t]) for t in sorted(bound(axis, "across", "down"))},
        "vertical": {t: dict(axis[t]) for t in sorted(bound(axis, "down", "across"))},
    }


def words(doc):
    return {k: sorted(doc[k]) for k in ("linkWords", "horizontal", "vertical")}


def main():
    new = derive()
    if sys.argv[1:] == ["--check"]:
        old = json.loads(OUT.read_text()) if OUT.exists() else {}
        stale = []
        for k, now in words(new).items():
            was = set(old.get(k) or {})
            add, drop = sorted(set(now) - was), sorted(was - set(now))
            if add or drop:
                stale.append(f"  {k}: +{add} -{drop}")
        if stale:
            print("tools/data/clue_joints.json no longer matches the corpus; run "
                  "python3 tools/build_clue_joints.py\n" + "\n".join(stale))
            sys.exit(1)
        print("clue_joints.json matches the corpus")
        return
    OUT.write_text(json.dumps(new, indent=1, sort_keys=False) + "\n")
    w = words(new)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(w['linkWords'])} link words, "
          f"{len(w['horizontal'])} horizontal, {len(w['vertical'])} vertical")


if __name__ == "__main__":
    main()
