def esc(s):
    return html.escape(str(s or ""), quote=True)


# Mirrors knownSetter() in app.js. A source that ships no byline gets
# "Unknown" from default_setter() in tools/series.py — a fact worth keeping in
# the data, but one that reads as a scraping failure wherever it is shown, so
# it is shown nowhere.
def known_setter(setter):
    return setter if setter and setter != "Unknown" else ""


def asset(rel):
    """An absolute, content-stamped URL for one of our own static files.

    Never write these out by hand. og.png was linked bare for a month; when the
    card's grid was redrawn the URL stayed identical, so every service that had
    already unfurled the site kept showing the old picture. The hash in the URL
    is what makes a corrected image reach someone who saw the wrong one.
    """
    return esc(asset_url(rel, BASE + "/"))


# Setters italicise titles and foreign words, and both the Guardian and the
# Independent ship that as markup inside the clue string: "Case for <i>Turandot</i>
# lyrics…". The app renders clue text as HTML and always has; these static pages
# were escaping it, so every such clue read "&lt;i&gt;Turandot&lt;/i&gt;" on the
# page that is supposed to be the readable one.
#
# So: escape everything, then put back exactly these tags. A whitelist and not a
# "don't escape clues" shortcut, because clue text is scraped from two
# publishers' feeds and is not ours to trust — anything they send that isn't on
# this list still comes out as visible text rather than as markup.
CLUE_TAGS = ("i", "b", "em", "strong", "span", "sub", "sup")
_CLUE_TAG_RE = re.compile(r"&lt;(/?)(" + "|".join(CLUE_TAGS) + r")&gt;")


def esc_clue(s):
    return _CLUE_TAG_RE.sub(r"<\1\2>", esc(s))


def puzzles():
    out = []
    for path in puzzle_files():
        out.append(read_puzzle_file(path))
    # Chronological, matching fetch_puzzle.reindex(). Sorting on the number was
    # the same thing while every puzzle was a cryptic; now that quiptics (~1,400)
    # sit alongside cryptics (~30,000) it would file every quiptic at the end of
    # time and make prev/next hop between series.
    out.sort(key=lambda p: (p.get("date") or 0, p.get("series", "cryptic") == "cryptic",
                            p["number"]), reverse=True)
    return out


# Titles and headings are built from tools/series.py rather than from a
# hardcoded "Guardian Cryptic", so a Quiptic page doesn't claim to be a cryptic
# and an Everyman page doesn't credit the wrong paper — Everyman is the
# Observer's Sunday puzzle, only syndicated onto the Guardian's site.
def kind(p):
    return series_meta.kind(p.get("series"), p["number"])


def position(p):
    """The number printed BESIDE the kind, which already names the volume.

    A book puzzle's stored number carries its volume (tools/series.py,
    volume * 1000 + position), so "Penguin Book 5 Cryptic No 5,018" would both
    name a number no book prints and say the volume twice. A feed puzzle's
    number is its position, so this is the publisher's own number there.
    """
    return series_meta.position_of(p.get("series") or "cryptic", p["number"])


def named(p):
    """"Guardian Penguin Book 5 Cryptic No 18" — the puzzle in full prose."""
    return f"{publisher(p)} {kind(p)} No {position(p):,}"


def display_number(p):
    """The number as a reader is shown it — "No 30,089", "Penguin book 5 No 18".

    Used wherever a number is printed with no kind beside it: the archive rows,
    the homepage list, prev/next. See display_number() in tools/series.py; a
    book's stored number carries its volume, and "No 5,018" names a puzzle no
    book prints.
    """
    return series_meta.display_number(p.get("series") or "cryptic", p["number"])


def publisher(p):
    # The number as well as the series: a book's paper is the BOOK's, and one
    # shelf reprints a dozen of them.
    return series_meta.publisher(p.get("series"), p["number"])


def papers(idx):
    """The papers this collection actually holds, commonest first.

    Site-wide copy said "Guardian" for a year because that was all there was;
    it kept saying it after the Independent and the Observer's Everyman
    arrived (2026-08-05), so the archive page's title, description and heading
    all named one paper above a list of three. Derived rather than written out:
    a sentence naming the collection cannot be true for long if a human has to
    remember to update it whenever a series is added.
    """
    counts = {}
    for p in idx["puzzles"]:
        if p.get("hasSolutions"):
            counts[publisher(p)] = counts.get(publisher(p), 0) + 1
    names = sorted(counts, key=lambda n: (-counts[n], n))
    if len(names) < 2:
        return names[0] if names else "broadsheet"
    return ", ".join(names[:-1]) + " and " + names[-1]


def assert_names_all_papers(where, text, idx):
    """No paper may be named in site-wide copy unless all of them are.

    The mechanical form of the rule above, for the pages a human still writes
    by hand. Naming one paper is fine on a puzzle page — that page IS one
    paper's puzzle — but in copy that describes the whole collection it is a
    claim about all of it, and a wrong one the moment a second paper lands.
    """
    present = {publisher(p) for p in idx["puzzles"] if p.get("hasSolutions")}
    named = {n for n in present if n in text}
    if named and named != present:
        raise SystemExit(
            f"{where}: names {sorted(named)} but the collection also holds "
            f"{sorted(present - named)}. Copy about the whole site names every "
            f"paper in it or none of them — see papers() in build_seo_pages.py.")


