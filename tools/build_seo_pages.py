# -------------------------------------------------------------------- sitemap

def sitemap(idx):
    urls = [(f"{BASE}/", "daily", "1.0", None),
            (f"{BASE}/puzzles/", "daily", "0.9", None),
            (f"{BASE}/learn/", "monthly", "0.8", None),
            (f"{BASE}/abbreviations/", "weekly", "0.8", None)]
    for p in idx["puzzles"]:
        if p.get("hasSolutions"):
            urls.append((f"{BASE}/puzzles/{p['id']}/", "monthly", "0.7",
                         datestr(p.get("date"), "%Y-%m-%d") or None))
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, freq, prio, lastmod in urls:
        out.append("  <url>")
        out.append(f"    <loc>{loc}</loc>")
        if lastmod:
            out.append(f"    <lastmod>{lastmod}</lastmod>")
        out.append(f"    <changefreq>{freq}</changefreq>")
        out.append(f"    <priority>{prio}</priority>")
        out.append("  </url>")
    out.append("</urlset>")
    return "\n".join(out) + "\n"


# ------------------------------------------------------- homepage crawl links

def homepage_nav(idx):
    """The links that give a crawler somewhere to go from the homepage.

    Without these the static pages exist but nothing points at them except the
    sitemap, and a sitemap-only URL is treated as a much weaker signal than one
    that is actually linked. Visible to readers too — it is a real index.
    """
    recent = [p for p in idx["puzzles"] if p.get("hasSolutions")][:12]
    items = "".join(
        f'<li><a href="puzzles/{p["id"]}/">No {p["number"]:,}'
        + (f' &middot; {esc(p.get("setter"))}' if p.get("setter") else "")
        + "</a></li>" for p in recent)
    return f"""{NAV_START}
<section class="seo-nav">
  <h2>Answers and explanations</h2>
  <p>Every clue of these puzzles is written up in full — answer, definition and wordplay.
     Start with <a href="learn/">how cryptic clues work</a>, learn the
     <a href="abbreviations/">standard abbreviations</a>, or browse
     <a href="puzzles/">all {sum(1 for p in idx["puzzles"] if p.get("hasSolutions"))} puzzles</a>.</p>
  <ul>{items}</ul>
</section>
{NAV_END}"""


def patch_homepage(idx):
    path = ROOT / "index.html"
    text = path.read_text(encoding="utf-8")
    # The <head> only: title, descriptions and the JSON-LD blurb are copy about
    # the site as a whole. The body below carries per-puzzle links, where naming
    # one paper is simply what that puzzle is.
    assert_names_all_papers("index.html <head>",
                            text.split("</head>", 1)[0], idx)
    nav = homepage_nav(idx)
    if NAV_START in text and NAV_END in text:
        new = re.sub(re.escape(NAV_START) + r".*?" + re.escape(NAV_END), lambda _: nav,
                     text, flags=re.S)
    else:
        new = text.replace("<footer>", nav + "\n\n<footer>", 1)
    return path, new


def legacy_redirects(solved):
    """A page at /puzzles/<bare number>/ for every puzzle, pointing at its id.

    Puzzle pages moved from /puzzles/30089/ to /puzzles/cryptic-30089/ on
    2026-08-19, when ids grew their series so two papers could not claim one
    directory. Those old URLs are indexed and shared, and GitHub Pages cannot
    answer with a 301, so each becomes a page that says where its puzzle is in
    the two ways that count: rel=canonical for a crawler, a meta refresh for a
    reader. Kept forever, not for a grace period — a link somebody sent a friend
    has no expiry.

    Built for every puzzle, not only the ones that predate the move, and the copy
    says "is at" rather than "has moved" for exactly that reason: a series added
    afterwards was never published under its bare number, and the first one
    (indysunday, 2026-08-19) got 52 pages announcing a move that never happened.
    A number is a number — the page's job is to say which puzzle it names.

    A number claimed by more than one paper offers the choice rather than
    guessing, which is the same rule resolve_puzzle() applies on the command
    line: an ambiguous number is a question, never a coin toss.
    """
    by_number = {}
    for p in solved:
        by_number.setdefault(str(p["number"]), []).append(p)
    out = {}
    for num, ps in sorted(by_number.items()):
        pretty = f"{int(num):,}"
        if len(ps) == 1:
            target = f"{BASE}/puzzles/{ps[0]['id']}/"
            title = f"No {pretty} — {publisher(ps[0])} {kind(ps[0])}"
            body = (f'<p>This puzzle is at '
                    f'<a href="{target}">{esc(target)}</a>.</p>')
            refresh = f'<meta http-equiv="refresh" content="0; url={esc(target)}">\n'
        else:
            target = f"{BASE}/puzzles/"
            title = f"No {pretty} — which paper?"
            body = ("<p>More than one paper has a No " + pretty + ":</p><ul>" + "".join(
                f'<li><a href="{BASE}/puzzles/{p["id"]}/">'
                f'{esc(publisher(p))} {esc(kind(p))} No {pretty}</a></li>' for p in ps)
                + "</ul>")
            refresh = ""
        out[PUZZLE_DIR / num / "index.html"] = (
            head(title, f"Where to find cryptic crossword No {pretty}.", target,
                 extra=refresh)
            + masthead([("Cryptic Teacher", "/"), ("Puzzles", "/puzzles/"),
                        (f"No {pretty}", "")])
            + f'<main class="static-main"><h1>{esc(title)}</h1>{body}</main>\n'
            + FOOTER + "</body>\n</html>\n")
    return out


# ------------------------------------------------------------------------ run

def outputs():
    idx = index_json()
    meta = {p["id"]: p for p in idx["puzzles"]}
    solved = [p for p in puzzles() if any(e.get("solution") for e in p["entries"])]

    files = {}
    for i, puz in enumerate(solved):
        # The list is newest-first, so "next" is the older neighbour.
        prev_p = solved[i - 1] if i > 0 else None
        next_p = solved[i + 1] if i + 1 < len(solved) else None
        files[PUZZLE_DIR / puz["id"] / "index.html"] = puzzle_page(
            puz, meta.get(puz["id"]), prev_p, next_p)
    for path, page in legacy_redirects(solved).items():
        files[path] = page
    files[PUZZLE_DIR / "index.html"] = hub_page(idx)
    files[ROOT / "learn" / "index.html"] = learn_page()
    files[ROOT / "abbreviations" / "index.html"] = abbreviations_page()
    files[ROOT / "sitemap.xml"] = sitemap(idx)
    path, text = patch_homepage(idx)
    files[path] = text
    assert_no_root_relative(files)
    return files


def assert_no_root_relative(files):
    """No generated link may start at /, because the site does not.

    GitHub Pages serves this out of /cryptic-teacher/; `/puzzles/` resolves to
    paultarjan.com/puzzles/, which 404s. Nothing in a browser catches that — the
    page renders fine and only the crawler notices — so it is checked here, where
    every generated href passes through. Links are absolute (BASE + path) or
    relative to the page; a leading slash is neither.
    """
    bad = []
    for path, text in files.items():
        if path.suffix != ".html":
            continue
        for m in re.finditer(r'(?:href|src)="(/[^/][^"]*)"', text):
            bad.append(f"{path.relative_to(ROOT)}: {m.group(1)}")
    if bad:
        raise SystemExit("root-relative links in generated pages (the site lives "
                         f"at {BASE}/, so these 404):\n  " + "\n  ".join(bad[:20]))


def main():
    files = outputs()
    check = "--check" in sys.argv
    stale = [p for p, text in files.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            for p in sorted(stale):
                print(f"STALE: {p.relative_to(ROOT)}")
            print("run python3 tools/build_seo_pages.py")
            return 1
        print(f"{len(files)} generated page(s) up to date")
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} page(s); {len(stale)} changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
