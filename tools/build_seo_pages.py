def outputs():
    idx = index_json()
    meta = {p["id"]: p for p in idx["puzzles"]}
    solved = [p for p in puzzles() if any(e.get("solution") for e in p["entries"])]

    files = {}
    # Kept by id as well as by path: the glossary links into these pages and
    # checks each anchor against the very text this run is about to write, not
    # against whatever is on disk from a previous one.
    pages = {}
    for i, puz in enumerate(solved):
        # The list is newest-first, so "next" is the older neighbour.
        prev_p = solved[i - 1] if i > 0 else None
        next_p = solved[i + 1] if i + 1 < len(solved) else None
        pages[puz["id"]] = puzzle_page(puz, meta.get(puz["id"]), prev_p, next_p)
        files[PUZZLE_DIR / puz["id"] / "index.html"] = pages[puz["id"]]
    for path, page in legacy_redirects(solved).items():
        files[path] = page
    for path, page in legacy_ids(solved).items():
        files[path] = page
    files[PUZZLE_DIR / "index.html"] = hub_page(idx)
    files.update(listing_pages(idx))
    files[ROOT / "learn" / "index.html"] = learn_page()
    files[ROOT / "abbreviations" / "index.html"] = abbreviations_page(solved, pages)
    files[ROOT / "sitemap.xml"] = sitemap(idx)
    path, text = patch_homepage(idx)
    files[path] = text
    # The manifest is hand-written and generates nothing, so it sat outside the
    # naming rule and went on describing a one-paper collection. It is copy
    # about the whole site — an installed icon's description — so it is held to
    # the same rule as the pages that are generated.
    assert_names_all_papers("site.webmanifest",
                            (ROOT / "site.webmanifest").read_text(encoding="utf-8"), idx)
    assert_no_root_relative(files)
    return files


def assert_no_root_relative(files):
    """No generated link may start at /.

    This was load-bearing when the site was served out of paultarjan.com/cryptic-teacher/,
    where `/puzzles/` resolved to the personal site and 404'd on every one of the
    70-odd puzzle pages. Since the move to its own host a leading slash would in
    fact resolve, so the check now guards a weaker thing: relative hrefs are what
    let the generated pages be opened straight off disk, and what made that move
    a one-line change to BASE instead of a rewrite. Keep it for the next move.

    Nothing in a browser catches a wrong link — the page renders fine and only a
    crawler notices — so it is checked here, where every generated href passes
    through. Links are absolute (BASE + path) or relative to the page.
    """
    bad = []
    for path, text in files.items():
        if path.suffix != ".html":
            continue
        for m in re.finditer(r'(?:href|src)="(/[^/][^"]*)"', text):
            bad.append(f"{path.relative_to(ROOT)}: {m.group(1)}")
    if bad:
        raise SystemExit("root-relative links in generated pages (the site lives "
                         f"at {BASE}/, so these 404):\n  " + "\n  ".join(bad[:20]))


def orphans(files):
    """Per-puzzle output directories under puzzles/ that this run does not write.

    Output is decided by the index, so the set of directories that should exist
    is known exactly on every run; a directory outside that set is one no future
    run will ever rewrite. The generator only ever wrote, so those accumulated
    silently — a renamed puzzle left its old page behind serving stale content
    at a live URL, with nothing on disk to say it was dead.

    The rule is narrow on purpose, because this walks the directory that also
    holds the site's real data:

      * only direct child DIRECTORIES of puzzles/, and the listing directories
        puzzles/series/<series>/<year>/, are candidates, so no flat
        puzzles/<series>-<number>.* file can be reached at all;
      * a directory qualifies only if its entire content is one index.html,
        which is the exact shape this generator creates;
      * and only if that index.html is not one this run is about to write.

    A bare-numeric directory is NOT an orphan: legacy_redirects() writes one for
    every puzzle number and always will. The test for a dead page is "this run
    does not write it", never a guess from the name.

    Anything that does not fit the shape is returned as a leftover rather than
    removed — an unexpected file under puzzles/ is a question, not a target.
    """
    series_dir = PUZZLE_DIR / "series"
    wanted = {p.parent for p in files} | {series_dir}
    dead, unexpected = [], []
    # series/<series>/<year>/ is the one nested shape, so it gets the same test.
    for d in sorted([*PUZZLE_DIR.iterdir(), *series_dir.glob("*/*")]):
        if not d.is_dir() or d in wanted:
            continue
        if [x.name for x in d.iterdir()] == ["index.html"]:
            dead.append(d)
        else:
            unexpected.append(d)
    return dead, unexpected


def main():
    files = outputs()
    check = "--check" in sys.argv
    stale = [p for p, text in files.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    dead, unexpected = orphans(files)
    for d in unexpected:
        print(f"LEFTOVER: {d.relative_to(ROOT)} is not a generated page directory "
              "— left alone")
    if check:
        for d in sorted(dead):
            print(f"ORPHAN: {d.relative_to(ROOT)}")
        if stale or dead:
            for p in sorted(stale):
                print(f"STALE: {p.relative_to(ROOT)}")
            print("run python3 tools/build_seo_pages.py")
            return 1
        print(f"{len(files)} generated page(s) up to date")
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    for d in dead:
        (d / "index.html").unlink()
        d.rmdir()
        if d.parent.parent == PUZZLE_DIR / "series" and not any(d.parent.iterdir()):
            d.parent.rmdir()          # a series with no listing pages left
    print(f"wrote {len(files)} page(s); {len(stale)} changed; "
          f"{len(dead)} orphan(s) removed")
    return 0


