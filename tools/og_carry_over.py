#!/usr/bin/env python3
"""One-off: move og/.manifest.json from the old card_key to the new one.

card_key used to hash salt + the puzzle's generated shim; it now hashes salt +
the entries the card is drawn from (make_og_card.card_key). Every manifest
entry written under the old key reads as stale under the new one, which would
redraw every card for nothing. So an entry is carried over, rewritten to its
new key with no redraw, only when it provably describes the puzzle as it is
today: it must equal the old key of the puzzle's CURRENT data, under the
salt the old make_og_card.py made, with the shim spelled either of the two
ways the shims were ever spelled while that script was in use (pretty-printed
before 05a3300, compact after it). Anything else is left alone and redraws
as usual.

Run by make_og.sh --all ahead of --stale. Idempotent: an entry already on the
new key is counted and skipped. Delete this file and its line in make_og.sh
once a deploy has run it; it is not part of make_og_card.py because any edit
to that file changes the salt and so redraws every card.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_og_card as og  # noqa: E402
from fetch_puzzle import read_puzzle_file, with_blog_facts  # noqa: E402

# make_og_card.py as it was when every existing manifest entry was written:
# its blob, and a commit on master that holds it, for a shallow CI checkout
# that has to fetch it.
OLD_SCRIPT_BLOB = "64fec1e3ef029558deac5aacacecaf0386c08a9e"
OLD_SCRIPT_COMMIT = "db09ff6905592a16c477390e8ca2f6aaaa8d54da"


def git(*args):
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, check=False)


def old_script():
    got = git("cat-file", "blob", OLD_SCRIPT_BLOB)
    if got.returncode:
        fetched = git("fetch", "--quiet", "--depth=1", "origin", OLD_SCRIPT_COMMIT)
        if fetched.returncode:
            raise SystemExit("og_carry_over: cannot fetch " + OLD_SCRIPT_COMMIT + ": "
                             + fetched.stderr.decode(errors="replace").strip())
        got = git("cat-file", "blob", OLD_SCRIPT_BLOB)
    if got.returncode:
        raise SystemExit("og_carry_over: no blob " + OLD_SCRIPT_BLOB + ": "
                         + got.stderr.decode(errors="replace").strip())
    return got.stdout


def old_salt():
    """make_og_card._salt() as the old script computed it."""
    h = hashlib.sha256()
    h.update(old_script())
    h.update(repr((og.FAMILIES, og.FALLBACK_FAMILY, og.LADDER)).encode("utf-8"))
    h.update(og.CARD_REGION.sub("", og.CARD.read_text(encoding="utf-8")).encode("utf-8"))
    return h


def old_shims(path):
    """The two spellings of this puzzle's shim the old key was taken over."""
    puzzle = read_puzzle_file(path)
    acquirer = (puzzle.get("provenance") or {}).get("acquiredBy") or "tools/fetch_puzzle.py"
    shown = with_blog_facts(puzzle)
    pretty = json.dumps(shown, indent=1, ensure_ascii=False)
    yield (f"// Generated by {acquirer} — puzzle © its original publisher.\n"
           "// Annotations (type/definition/indicators/blocks/walkthrough) are original\n"
           "// to this project. Edit the annotation objects freely; keep the JSON markers.\n"
           "window.CRYPTIC_PUZZLES = window.CRYPTIC_PUZZLES || {};\n"
           f'window.CRYPTIC_PUZZLES["{puzzle["id"]}"] = /*JSON-START*/ {pretty} /*JSON-END*/;\n')
    compact = json.dumps(shown, ensure_ascii=False, separators=(",", ":"))
    yield (f"// Generated by {acquirer} from {path.name}. Puzzle © its original publisher.\n"
           "window.CRYPTIC_PUZZLES = window.CRYPTIC_PUZZLES || {};\n"
           f'window.CRYPTIC_PUZZLES["{puzzle["id"]}"] = {compact};\n')


def main():
    have = og._manifest()
    if not have:
        print("og_carry_over: no manifest, nothing to carry over")
        return 0
    new_salt, was_salt = og._salt(), old_salt()
    counts = {"already on the new key": 0, "carried over": 0, "will redraw": 0}
    for pid in og.eligible():
        new = og.card_key(pid, new_salt)
        if have.get(pid) == new:
            counts["already on the new key"] += 1
            continue
        path = og.puzzle_file(pid)
        olds = set()
        for text in old_shims(path):
            h = was_salt.copy()
            h.update(text.encode("utf-8"))
            olds.add(h.hexdigest())
        if (REPO / f"og/{pid}.png").exists() and have.get(pid) in olds:
            have[pid] = new
            counts["carried over"] += 1
        else:
            counts["will redraw"] += 1
    og.MANIFEST.write_text(json.dumps(have, indent=1, sort_keys=True), encoding="utf-8")
    print("og_carry_over: " + ", ".join(f"{v} {k}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
