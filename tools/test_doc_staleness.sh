#!/bin/bash
# Do the hand-written docs stay free of numbers that go stale?
#
#     bash tools/test_doc_staleness.sh
#
# Docs describe how and why, not current numbers. "About 17,000 puzzles are
# annotated" is false next week; "currently" and "as of" announce a snapshot.
# A live number belongs on the site's /progress/ page or in a region
# tools/build_readme.py generates, and a doc points there instead. Dated
# history stays true ("on 08-08 the nightly moved to Opus"), so a line that
# carries a MM-DD date, or follows one that does, is exempt. Generated regions
# (between <!-- NAME-START ... --> and <!-- NAME-END -->) and code fences are
# skipped: build_readme.py rewrites the first, and the second is not prose.
#
# It checks README.md, APP.md, BACKFILLS.md, STYLE.md, tools/data/README.md
# and docs/*.md, and first checks itself on a fixture.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import glob
import re
import sys

NOUNS = r"(?:puzzles|clues|commits|checks|lines|editions|series|hints|annotations)"
DENY = [
    ("an approximate live count",
     re.compile(r"\b(?:about|roughly|around|nearly|almost|approximately|some|over|~) ?"
                r"[0-9][0-9,.]*k? " + NOUNS + r"\b", re.I)),
    ("an exact corpus count",
     re.compile(r"\b[0-9]{1,3}(?:,[0-9]{3})+ " + NOUNS + r"\b", re.I)),
    ("a snapshot word",
     re.compile(r"\b(?:currently|as of|right now|at the time of writing|at present)\b", re.I)),
]
DATED = re.compile(r"\b(?:20[0-9]{2}-)?[01][0-9]-[0-3][0-9]\b")
START = re.compile(r"<!-- [A-Z0-9_]+-START\b")
END = re.compile(r"<!-- [A-Z0-9_]+-END -->")


def hits(text):
    """(line number, why, match) for each stale-looking phrase in prose."""
    out = []
    generated = fenced = False
    prev = ""
    for n, line in enumerate(text.splitlines(), 1):
        if START.search(line):
            generated = True
        if generated:
            if END.search(line):
                generated = False
            prev = ""
            continue
        if line.lstrip().startswith("```"):
            fenced = not fenced
            prev = ""
            continue
        if fenced:
            continue
        if not (DATED.search(line) or DATED.search(prev)):
            for why, rx in DENY:
                m = rx.search(line)
                if m:
                    out.append((n, why, m.group(0)))
                    break
        prev = line
    return out


FIXTURE = """\
About 17,000 puzzles are annotated.
The burn currently runs hourly.
On 10-12 the A/B graded about 120 puzzles,
and found about 60 clues wrong.
<!-- CORPUS-START generated by tools/build_readme.py -->
about 51,000 puzzles across 25 series
<!-- CORPUS-END -->
```
as of today
```
The validator runs its checks on every write.
"""
got = [n for n, _, _ in hits(FIXTURE)]
if got != [1, 2]:
    print(f"FAIL: self-test flagged lines {got}, want [1, 2]", file=sys.stderr)
    sys.exit(1)

files = ["README.md", "APP.md", "BACKFILLS.md", "STYLE.md", "tools/data/README.md"] + sorted(glob.glob("docs/*.md"))
bad = 0
for f in files:
    try:
        text = open(f, encoding="utf-8").read()
    except FileNotFoundError:
        continue
    for n, why, m in hits(text):
        bad += 1
        print(f"{f}:{n}: {why}: {m!r}", file=sys.stderr)
if bad:
    print(f"FAIL: {bad} number(s) or snapshot word(s) that go stale; say how and why, "
          "point to /progress/ or a build_readme.py region for live counts, "
          "or date it (MM-DD) if it is history", file=sys.stderr)
    sys.exit(1)
print(f"ok: {len(files)} hand-written docs hold no live count or snapshot word")
PY
