#!/usr/bin/env python3
"""Assemble an original puzzle file from a grid fill plus authored clues.

The grid fill (tools/grid_fill.py) already knows the geometry: where every
entry starts, how long it is, and which word fills it. What it cannot know is
the clue. This script marries the two halves so the geometry is never retyped
by hand — retyping is how a solution and a position drift apart.

Output goes to puzzles/<ID>.js in exactly the format tools/fetch_puzzle.py
produces for Guardian puzzles, so the same validator, the same app and the same
smoke test apply to our own puzzles with no special cases. IDs for authored
puzzles start with a letter (A001), which keeps them out of the daily
validator sweep (it globs "[0-9]*.js") until we choose to publish one.

  python3 tools/build_authored_puzzle.py \
      --fill tools/data/sample_fill_11.json \
      --clues tools/data/authored_A001_clues.json \
      --id A001 --name "Cryptic Teacher No 1" --setter "Cryptic Teacher"
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUZZLE_DIR = ROOT / "puzzles"

HEADER = """\
// Generated by tools/build_authored_puzzle.py — puzzle and annotations are
// original to this project. Grid geometry comes from a tools/grid_fill.py run;
// clues come from the paired *_clues.json. Edit clues there and rebuild, so the
// geometry and the clues can never drift apart.
window.CRYPTIC_PUZZLES = window.CRYPTIC_PUZZLES || {};
window.CRYPTIC_PUZZLES[%s] = /*JSON-START*/ """


def build(fill_path, clues_path, puzzle_id, name, setter, date_ms):
    fill = json.loads(Path(fill_path).read_text())
    clues = json.loads(Path(clues_path).read_text())

    entries = []
    missing = []
    for e in fill["entries"]:
        eid = e["id"]
        spec = clues.get(eid)
        if not spec:
            missing.append(eid)
            continue
        ann = spec["annotation"]
        # The annotation's answer must be the letters the grid actually holds.
        # A silent mismatch here would put a clue for one word under another.
        letters = "".join(c for c in ann["answer"].upper() if c.isalpha())
        if letters != e["solution"]:
            sys.exit(
                f"{eid}: annotation answer {ann['answer']!r} gives {letters}, "
                f"but the grid holds {e['solution']}"
            )
        entries.append({
            "id": eid,
            "number": e["number"],
            "direction": e["direction"],
            "position": e["position"],
            "length": e["length"],
            "clue": spec["clue"],
            "group": [eid],
            "solution": e["solution"],
            "annotation": ann,
        })

    if missing:
        sys.exit("no clue written for: " + ", ".join(missing))

    extra = set(k for k in clues if not k.startswith("_")) - {e["id"] for e in entries}
    if extra:
        sys.exit("clues written for entries not in the fill: " + ", ".join(sorted(extra)))

    entries.sort(key=lambda e: (e["number"], e["direction"]))
    size = fill["size"]
    return {
        "id": puzzle_id,
        "number": puzzle_id,
        "series": "authored",
        "name": name,
        "setter": setter,
        "date": date_ms,
        "dimensions": {"cols": size, "rows": size},
        "sourceUrl": "",
        "entries": entries,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fill", default="tools/data/sample_fill_11.json")
    ap.add_argument("--clues", required=True)
    ap.add_argument("--id", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--setter", default="Cryptic Teacher")
    ap.add_argument("--date", type=int, required=True,
                    help="publication date in epoch milliseconds")
    args = ap.parse_args()

    puzzle = build(args.fill, args.clues, args.id, args.name, args.setter, args.date)
    out = PUZZLE_DIR / f"{args.id}.js"
    body = json.dumps(puzzle, indent=1, ensure_ascii=False)
    out.write_text(HEADER % json.dumps(args.id) + body + " /*JSON-END*/;\n")
    print(f"wrote {out} — {len(puzzle['entries'])} entries")


if __name__ == "__main__":
    main()
