#!/usr/bin/env python3
"""A census of every whole-clue wordplay shape in the corpus, and whether each one makes sense.

    nice -n 19 python3 tools/clue_shapes.py            # rewrite docs/CLUE_SHAPES.md (about 5 minutes)
    python3 tools/clue_shapes.py --dump /tmp/x.json    # also write every skeleton, with 3 example clues
    python3 tools/clue_shapes.py --check               # judgement file only: valid, and every pattern still matches

tools/wordplay.py says what each op means and tools/validate_annotations.py
checks a clue's letters; neither looks at a clue's tree as a whole. This does.
Every annotated clue's tree is reduced to a SKELETON: the op tree with each
leaf abstracted to a type, so two clues built the same way share one.

    ana(V)        an anagram of verbatim clue words      (A+S)   a charade of an abbreviation and a synonym
    ins(S,A)      a synonym with an abbreviation inside  ana?(..) an op the tree could not check ("?")

Leaf types, read off the leaf alone:
    V verbatim: no `gives`, or gives is the words' own letters (also: any fodder under an
      anagram, hidden or letter-selection op, whose `gives` is only what the op picks)
    F folded: longer `gives` that is part of the words' letters, or the words part of `gives`, so the
      leaf has swallowed a link word, an indicator or a selection (and says it gave)
    A short: gives of one or two letters (an abbreviation, a symbol, a selection)
    S synonym: any other `gives`
    B bare letters, no clue words (the letters a deletion names)
    U an unchecked leaf ("unchecked": true; its gives is taken as filed)
    D under a cryptic definition only: a leaf whose words repeat, or contain, another leaf's
Two coarser groupings are computed from the skeleton string (tier1, tier2): the set
of mechanisms, and the op tree with charades and leaf types collapsed. The doc opens
with them; the skeleton tables and the not-ok sections stay, for finding errors.

A charade is written (a+b+c), any other op name(children). Besides the skeleton a
clue has a DEFINITION descriptor: how many definitions and where (S start, E end,
W the whole clue, M middle), and "&lit" when andLit is set or one definition is
the whole clue.

The numbers, tables and examples in docs/CLUE_SHAPES.md are generated. The
JUDGEMENTS ("does this shape make sense?", why, the right shape) are not: they
live in tools/data/clue_shape_verdicts.json, keyed by exact skeleton or by a
regular expression over skeletons, and the doc lists at its top every common
skeleton that has none, so a regeneration keeps what was decided and shows what
is new. Verdicts: ok, rare (legitimate, setters seldom use it), redundant (could be
written simpler), mislabelled (the mechanism is stored as another one),
implausible (no real mechanism), unverified (an unchecked node).

Streaming, stdlib only, one process; run it under `nice -n 19`.
"""
import argparse
import collections
import json
import re
import sys
from pathlib import Path

import puzzle_paths
import wordplay

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "CLUE_SHAPES.md"
VERDICTS = ROOT / "tools" / "data" / "clue_shape_verdicts.json"
START = "<!-- CLUE_SHAPES-START generated by tools/clue_shapes.py: do not edit -->"
END = "<!-- CLUE_SHAPES-END -->"
KINDS = ("ok", "rare", "redundant", "mislabelled", "implausible", "unverified")
SHORT = {"anagram": "ana", "reversal": "rev", "container": "ins", "deletion": "del", "hidden": "hid",
         "homophone": "sound", "spoonerism": "spoon", "substitution": "sub", "cycling": "cyc",
         "cryptic": "cdef", "rebus": "rebus", "composite": "comp", "reverse": "reverse", "palindrome": "pal", "first": "first", "last": "last", "middle": "mid",
         "outer": "outer", "alternate": "alt", "regular": "reg", "nth": "nth"}
FODDER_OPS = {"anagram", "composite", "hidden", *wordplay.SELECT}
UNJUDGED_FROM = 150   # a skeleton this common with no verdict is listed at the top
TOP = 80
TOP1 = 30    # tier-1 rows in the doc
TOP2 = 40    # tier-2 rows in the doc


def letters(s):
    return re.sub(r"[^A-Z]", "", (s or "").upper())


def leaf_type(node, parent_op):
    if node.get("unchecked"):
        return "U"
    if "words" not in node:
        return "B"
    w, g = letters(node["words"]), letters(node.get("gives"))
    if node.get("gives") is None or g == w:
        return "V"
    related = bool(g) and (g in w or w in g)
    if parent_op in FODDER_OPS:
        return "V" if related else ("A" if len(g) <= 2 else "S")
    if len(g) <= 2:
        return "A"
    return "F" if related else "S"


def analyse(node, parent_op=None):
    """(skeleton, depth, ops, non-charade ops list, unindicated ops, unchecked nodes, pairs)."""
    if "op" not in node:
        t = leaf_type(node, parent_op)
        return t, 0, 0, [], 0, int(t == "U"), []
    op = node["op"]
    kids = [analyse(p, op) for p in wordplay.parts_of(node)]
    if op == "cryptic":
        ws = [letters(p.get("words")) for p in wordplay.parts_of(node)]
        for i, k in enumerate(kids):
            if k[0] == "V" and ws[i] and any(j != i and ws[j] and (ws[i] in ws[j] or ws[j] in ws[i])
                                              for j in range(len(ws))):
                kids[i] = ("D",) + k[1:]
    name = "" if op == "charade" else SHORT.get(op, op) + ("?" if node.get("unchecked") else "")
    body = ("+" if op == "charade" else ",").join(k[0] for k in kids)
    sk = f"({body})" if op == "charade" else f"{name}({body})"
    ncc = ([] if op == "charade" else [op]) + [o for k in kids for o in k[3]]
    noind = int(op not in ("charade", "cryptic", "rebus", "reverse", "palindrome") and not node.get("indicators"))
    pairs = [(op, c["op"]) for c in wordplay.parts_of(node) if "op" in c] + [p for k in kids for p in k[6]]
    return (sk, 1 + max([k[1] for k in kids] or [0]), 1 + sum(k[2] for k in kids), ncc,
            noind + sum(k[4] for k in kids), int(bool(node.get("unchecked"))) + sum(k[5] for k in kids), pairs)


def compact(node):
    """The tree on one line, close to the annotator's expression."""
    if "op" not in node:
        w, g = node.get("words"), node.get("gives")
        if w is None:
            return g or "?"
        return f"[{w}]" if g is None or letters(g) == letters(w) else f"[{w}]{g}"
    parts = [compact(p) for p in wordplay.parts_of(node)]
    ind = "".join(f"<{i.get('text')}>" for i in node.get("indicators") or [])
    if node["op"] == "charade":
        return "(" + " + ".join(parts) + ")" + ind
    return SHORT.get(node["op"], node["op"]) + ind + "(" + ", ".join(parts) + ")"


def family(node, ndefs, sk, depth, ncc):
    if node is None:
        return "double definition" if ndefs >= 2 else "no wordplay"
    if "op" not in node:
        return "single leaf"
    if node["op"] == "cryptic":
        return "cryptic definition"
    if node["op"] == "rebus":
        return "rebus"
    if node["op"] == "reverse":
        return "reverse clue"
    if not ncc:
        return "charade, nested" if depth > 1 else "charade"
    u = sorted(set(ncc))
    sel = set(wordplay.SELECT)
    if len(ncc) >= 4:
        return "compound, 4+ ops"
    if len(ncc) == 3:
        return "compound, 3 ops"
    if len(ncc) == 2:
        if set(u) == {"anagram", "container"}:
            return "container with anagram"
        return "compound, 2 ops"
    op = ncc[0]
    base = "letter selection" if op in sel else {"anagram": "anagram", "container": "container", "hidden": "hidden",
                                                 "reversal": "reversal", "deletion": "deletion",
                                                 "homophone": "homophone"}.get(op, op)
    if node["op"] == "charade":
        return "anagram plus extra" if op == "anagram" else f"{base} in a charade"
    if op == "anagram" and node["op"] == "anagram" and any(c.get("op") == "charade" for c in wordplay.parts_of(node)):
        return "anagram of a charade"
    return base


def definition_key(ann, clue):
    defs = ann.get("definitions") or []
    pos = ""
    for d in defs:
        at, n = d.get("at"), len(d.get("text") or "")
        if at is None:
            pos += "?"
            continue
        start, end = at <= 1, at + n >= len(clue) - 2
        pos += "W" if start and end else "S" if start else "E" if end else "M"
    return f"{len(defs)}d:{pos or '-'}" + ("&lit" if ann.get("andLit") or "W" in pos else "")


class Census:
    def __init__(self):
        self.n = self.files = 0
        self.shapes = {}                       # skeleton -> [n, examples, noind, unchecked, defs, series]
        self.fam = {}                          # family -> [n, examples, series, unchecked, noind]
        self.depth, self.nops, self.nncc = collections.Counter(), collections.Counter(), collections.Counter()
        self.mdepth = collections.Counter()
        self.combos, self.pairs = collections.Counter(), {}
        self.series = collections.defaultdict(collections.Counter)
        self.leaves, self.defs = collections.Counter(), collections.Counter()
        self.sdepth = collections.defaultdict(collections.Counter)

    def add(self, series, pid, entry):
        ann = entry.get("annotation")
        if not ann:
            return
        wp, defs = ann.get("wordplay"), ann.get("definitions") or []
        if wp is None and len(defs) < 2:
            return
        self.n += 1
        clue = (entry.get("clue") or {}).get("text", "")
        cid = f"{pid}#{entry.get('number')}{(entry.get('direction') or '?')[:1]}"
        dk = definition_key(ann, clue)
        if wp is None:
            sk, depth, nops, ncc, noind, unch, pairs, line = "DD", 0, 0, [], 0, 0, [], ""
        else:
            sk, depth, nops, ncc, noind, unch, pairs = analyse(wp)
            line = compact(wp)
        ex = [cid, clue, entry.get("solution", ""), line]
        r = self.shapes.setdefault(sk, [0, [], 0, 0, collections.Counter(), collections.Counter()])
        r[0] += 1
        if len(r[1]) < 3 and (len(r[1]) == 0 or all(x[0].split("-")[0] != series for x in r[1])
                              or r[0] > 50 and len(r[1]) < 3):
            r[1].append(ex)
        r[2] += int(bool(noind))
        r[3] += int(bool(unch))
        r[4][dk] += 1
        r[5][series] += 1
        fam = family(wp, len(defs), sk, depth, ncc)
        f = self.fam.setdefault(fam, [0, [], collections.Counter(), 0, 0])
        f[0] += 1
        if len(f[1]) < 3:
            f[1].append(ex)
        f[2][series] += 1
        f[3] += int(bool(unch))
        f[4] += int(bool(noind))
        self.depth[depth] += 1
        self.mdepth[depth_of(sk)] += 1
        self.nops[nops] += 1
        self.nncc[len(ncc)] += 1
        self.sdepth[series][depth] += 1
        self.series[series]["_n"] += 1
        self.series[series]["fam:" + fam] += 1
        self.series[series]["def:" + dk] += 1
        if ncc:
            self.combos["+".join(sorted(set(ncc))) + (f" x{len(ncc)}" if len(set(ncc)) < len(ncc) else "")] += 1
        for p in set(pairs):
            q = self.pairs.setdefault(p, [0, ex])
            q[0] += 1
        for t in re.findall(r"[VFASBUD]", re.sub(r"[a-z?]+\(", "(", sk)):
            self.leaves[t] += 1
        self.defs[dk] += 1

    def run(self, files=None):
        for path in files or puzzle_paths.puzzle_files():
            try:
                pz = json.loads(Path(path).read_text())
            except (OSError, ValueError):
                continue
            self.files += 1
            for e in pz.get("entries") or []:
                self.add(Path(path).parent.parent.name, pz.get("id") or Path(path).stem, e)
        return self


# ---- verdicts ------------------------------------------------------------------------------------

def load_verdicts():
    try:
        v = json.loads(VERDICTS.read_text())
    except OSError:
        v = {}
    v.setdefault("shapes", {})
    v.setdefault("patterns", [])
    v.setdefault("families", {})
    return v


def check_verdicts(v):
    """Problems with the judgement file: an unknown verdict, a pattern that does not compile."""
    bad = []
    for k, r in v["shapes"].items():
        if r.get("verdict") not in KINDS:
            bad.append(f"shape {k}: verdict {r.get('verdict')!r}")
    for r in v["patterns"]:
        if r.get("verdict") not in KINDS:
            bad.append(f"pattern {r.get('name')}: verdict {r.get('verdict')!r}")
        try:
            re.compile(r.get("re", "."))
        except (KeyError, re.error) as e:
            bad.append(f"pattern {r.get('name')}: {e}")
        for k in ("name", "why"):
            if not r.get(k):
                bad.append(f"pattern {r.get('name')}: no {k}")
    return bad


def depth_of(sk):
    """How deep ops nest in a skeleton; a charade's brackets are not counted, only named ops."""
    d = m = 0
    named = []
    for i, ch in enumerate(sk):
        if ch == "(":
            named.append(i > 0 and (sk[i - 1].isalpha() or sk[i - 1] == "?"))
            if named[-1]:
                d += 1
                m = max(m, d)
        elif ch == ")":
            if named.pop():
                d -= 1
    return m


def mechanisms_of(sk):
    return len(re.findall(r"[a-z]+\??\(", sk))


def matches(p, rx, sk):
    if not rx.search(sk):
        return False
    d, m = depth_of(sk), mechanisms_of(sk)
    return (d >= p.get("depth_min", 0) and d <= p.get("depth_max", 99)
            and m >= p.get("mech_min", 0) and m <= p.get("mech_max", 99))


def judge(sk, v, pats):
    """(verdict row, group name) for a skeleton, or (None, None)."""
    r = v["shapes"].get(sk)
    if r:
        return r, r.get("group") or sk
    for p, rx in pats:
        if matches(p, rx, sk):
            return p, p["name"]
    return None, None


# ---- coarser groupings of a skeleton -------------------------------------------------------------

def parse_skeleton(sk):
    """A skeleton string as a tree: ("leaf",), ("+", kids) for a charade, (op, kids) for any other op."""
    pos = 0

    def node():
        nonlocal pos
        m = re.compile(r"([a-z]*)(\??)\(").match(sk, pos)
        if not m:
            if pos < len(sk) and sk[pos] not in ",+)":
                pos += 1
            return ("leaf", [])
        pos = m.end()
        kids = []
        while True:
            kids.append(node())
            ch = sk[pos] if pos < len(sk) else ")"
            pos += 1
            if ch == ")":
                break
        return (m.group(1) or "+", kids)
    return node()


COARSE = {o: "select" for o in ("first", "last", "mid", "outer", "alt", "reg", "nth")}
MAXOPS = 3   # a tree with more op nodes than this is one group in tier 2
MANY = 3   # a clue using more distinct mechanisms than this is one group in tier 1


def op_names(t):
    out = [] if t[0] in ("leaf", "+") else [COARSE.get(t[0], t[0])]
    for k in t[1]:
        out += op_names(k)
    return out


def tier1(sk):
    """The mechanism set: which non-charade ops the clue uses, in any nesting or number."""
    if sk == "DD":
        return "double definition"
    ops = sorted(set(op_names(parse_skeleton(sk))))
    if len(ops) > MANY:
        return f"{MANY + 1}+ different ops"
    return " + ".join(ops) if ops else "charade only"


def _mech(t, top=True):
    """Mechanism tree text: leaves collapse to x, a charade of leaves is x, children order-free and deduplicated."""
    name, kids = t
    if name == "leaf":
        return "x"
    sub = sorted({_mech(k, name == "+" and top) for k in kids})
    if name == "+":
        ops = [s for s in sub if s != "x"]
        if not ops:
            return "x"
        return "+[" + ",".join(ops) + "]" if top else ops[0] if len(ops) == 1 else ",".join(ops)
    return f"{COARSE.get(name, name)}({','.join(sub)})"


def tier2(sk):
    """The mechanism tree: op nesting with each charade collapsed, leaf types and definition placement dropped."""
    if sk == "DD":
        return "DD"
    m = _mech(parse_skeleton(sk))
    return m if len(re.findall(r"[a-z]+\(", m)) <= MAXOPS else f"{MAXOPS + 1}+ ops"


# ---- the document --------------------------------------------------------------------------------

def pct(n, total):
    return f"{100 * n / total:.2f}%" if total else "-"


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def ex_line(e, width=150):
    cid, clue, sol, line = e
    s = f"`{cid}` {clue} ({sol})" + (f" = `{line}`" if line else "")
    return s if len(s) <= width * 2 else s[:width * 2] + "..."


def rollup(c, v, pats, key):
    """Fold the skeletons into the groups `key` names: clues, skeletons, commonest skeleton."""
    g = {}
    for sk, r in c.shapes.items():
        e = g.setdefault(key(sk), {"n": 0, "skels": 0, "top": (sk, r), "t2": set()})
        e["n"] += r[0]
        e["skels"] += 1
        if r[0] > e["top"][1][0]:
            e["top"] = (sk, r)
        e["t2"].add(tier2(sk))
    return g


def coverage(counts, n):
    cum, hit = 0, {}
    for i, x in enumerate(sorted(counts, reverse=True), 1):
        cum += x
        for m in (0.5, 0.9, 0.99):
            if m not in hit and cum >= m * n:
                hit[m] = i
    return hit


def tier_sections(c, v, pats, w):
    n = c.n
    t1, t2 = rollup(c, v, pats, tier1), rollup(c, v, pats, tier2)
    w("## Three ways to group the shapes")
    w("")
    w("The skeleton (tier 3) keeps charade order and arity and every leaf type, so there are thousands. "
      "Two coarser groupings sit above it; each is computed from the skeleton, so the verdicts still key on tier 3, "
      "and the full skeleton tables further down stay as the place to look for errors.")
    w("")
    w("- **Tier 1, mechanism set**: which non-charade ops the clue uses, in any number and nesting. The letter "
      "selections (`first last mid outer alt reg nth`) count as one op, `select`; a clue with more than "
      f"{MANY} different ops is one group; `charade only` is a clue with no other op.")
    w("- **Tier 2, mechanism tree**: the op nesting with each leaf (any type) written `x`, siblings sorted and "
      "deduplicated so order and arity vanish, a charade that is only leaves written `x`, and a charade of ops "
      "written `+[...]` at the top of the tree (a charade that merely builds one operand of an op is dropped). "
      "`ins(ana(x),x)` (an anagram put inside a word) and `ana(ins(x))` (an anagram of a container) stay "
      f"distinct. A tree of more than {MAXOPS} op nodes is one group, `{MAXOPS + 1}+ ops`. Definition placement "
      "is dropped.")
    w("- **Tier 3, skeleton**: the exact skeleton, as in the tables further down.")
    w("")
    w("| tier | groups | cover 50% | cover 90% | cover 99% | groups with one clue |")
    w("|---|---:|---:|---:|---:|---:|")
    for name, g in (("1 mechanism set", t1), ("2 mechanism tree", t2),
                    ("3 skeleton", {k: {"n": r[0]} for k, r in c.shapes.items()})):
        h = coverage([e["n"] for e in g.values()], n)
        w(f"| {name} | {len(g):,} | {h.get(0.5, '-')} | {h.get(0.9, '-')} | {h.get(0.99, '-')} | "
          f"{sum(1 for e in g.values() if e['n'] == 1):,} |")
    w("")
    w("### Tier 1: mechanism sets")
    w("")
    w("| # | mechanisms | clues | share | cumulative | tier-2 groups | skeletons | example |")
    w("|---:|---|---:|---:|---:|---:|---:|---|")
    cum = 0
    for i, (k, e) in enumerate(sorted(t1.items(), key=lambda kv: -kv[1]["n"])[:TOP1], 1):
        cum += e["n"]
        w(f"| {i} | {esc(k)} | {e['n']:,} | {pct(e['n'], n)} | {pct(cum, n)} | {len(e['t2']):,} | {e['skels']:,} | "
          f"{esc(ex_line(e['top'][1][1][0], 55))} |")
    w("")
    if len(t1) > TOP1:
        w(f"{len(t1) - TOP1} smaller sets not shown.")
        w("")
    w(f"### Tier 2: the {TOP2} commonest mechanism trees")
    w("")
    w("`x` is any leaf. Skeletons is how many tier-3 skeletons fold into the tree.")
    w("")
    w("| # | tree | clues | share | cumulative | skeletons | commonest skeleton | example |")
    w("|---:|---|---:|---:|---:|---:|---|---|")
    cum = 0
    for i, (k, e) in enumerate(sorted(t2.items(), key=lambda kv: -kv[1]["n"])[:TOP2], 1):
        cum += e["n"]
        w(f"| {i} | `{esc(k)}` | {e['n']:,} | {pct(e['n'], n)} | {pct(cum, n)} | {e['skels']:,} | "
          f"`{esc(e['top'][0])}` | {esc(ex_line(e['top'][1][1][0], 45))} |")
    w("")


def build_doc(c, v):
    pats = [(p, re.compile(p.get("re", "."))) for p in v["patterns"]]
    n = c.n
    ranked = sorted(c.shapes.items(), key=lambda kv: -kv[1][0])
    out = []
    w = out.append
    w("# Clue shapes")
    w("")
    w(START)
    w("")
    w(f"Every annotated clue's wordplay tree reduced to a skeleton (op tree, leaves abstracted to a type), "
      f"over {n:,} clues in {c.files:,} puzzles: {len(ranked):,} distinct skeletons, folded into coarser groups below. "
      "Generated by `tools/clue_shapes.py` (`nice -n 19 python3 tools/clue_shapes.py`, about five minutes); "
      "the judgements come from `tools/data/clue_shape_verdicts.json`, which the tool never writes.")
    w("")
    w("Leaf types: **V** verbatim clue words (and any fodder under an anagram, hidden or selection op), "
      "**F** folded (`gives` is part of the words, or the words part of `gives`: a link word, indicator or "
      "selection swallowed by the leaf), **A** one or two letters from other words (abbreviation, symbol), "
      "**S** synonym or other `gives`, **B** bare letters with no clue words, **U** unchecked leaf. "
      "`(a+b)` is a charade; `ana`, `ins` (container), `del`, `rev`, `hid`, `sound`, `spoon`, `sub`, `cyc`, `pal`, "
      "`cdef` (cryptic definition), `rebus` (a picture of letters), `comp` (composite anagram), `reverse` (reverse clue), `first last mid outer alt reg nth` (letter selection) name the other ops; "
      "`?` after an op name means its node is unchecked. Definition key: `2d` is the number of "
      "definitions, then where each sits (S start, E end, W whole clue, M middle); `&lit` when andLit is set.")
    w("")
    tier_sections(c, v, pats, w)
    # unjudged
    unj = [(sk, r) for sk, r in ranked if r[0] >= UNJUDGED_FROM and judge(sk, v, pats)[0] is None
           and sk not in ("DD",)]
    w("## Skeletons with no verdict yet")
    w("")
    if unj:
        w(f"{len(unj)} skeletons of at least {UNJUDGED_FROM} clues have no entry in the judgement file "
          "(listed by count; add a row to `shapes` or a pattern):")
        w("")
        for sk, r in unj[:40]:
            w(f"- `{sk}` ({r[0]:,}): {ex_line(r[1][0], 90)}")
        if len(unj) > 40:
            w(f"- ... and {len(unj) - 40} more")
    else:
        w(f"None: every skeleton of at least {UNJUDGED_FROM} clues has a verdict.")
    w("")
    # senseless shapes
    groups = {}
    for sk, r in ranked:
        row, name = judge(sk, v, pats)
        if not row or row["verdict"] == "ok":
            continue
        g = groups.setdefault(name, {"row": row, "n": 0, "skels": 0, "top": None})
        g["n"] += r[0]
        g["skels"] += 1
        if g["top"] is None:
            g["top"] = (sk, r)
    w("## Still being fixed")
    w("")
    bad = sorted(groups.items(), key=lambda kv: -kv[1]["n"])
    tot = sum(g["n"] for _, g in bad)
    if not bad:
        w("None: every skeleton is judged ok.")
        w("")
    else:
        w(f"{tot:,} clues ({pct(tot, n)}) have a skeleton judged other than ok, in {len(bad)} groups, "
          "ranked by clues. These are errors in the repair queue (`tools/data/shape_reannotate.json`), not a "
          "standing statistic; the list shrinks to None as the queue drains. `right` is the shape the clue should have.")
        w("")
    for i, (name, g) in enumerate(bad, 1):
        row, (sk, r) = g["row"], g["top"]
        w(f"### {i}. {name}: {g['n']:,} clues ({pct(g['n'], n)}), {row['verdict']}")
        w("")
        w(f"- why: {row['why']}")
        if row.get("right"):
            w(f"- right: {row['right']}")
        w(f"- {g['skels']} skeleton{'s' if g['skels'] != 1 else ''}; commonest `{sk}` ({r[0]:,})")
        for e in r[1]:
            w(f"  - {ex_line(e)}")
        w("")
    # families
    w("## Families")
    w("")
    w("| family | clues | share | unchecked | unindicated | example |")
    w("|---|---:|---:|---:|---:|---|")
    for name, f in sorted(c.fam.items(), key=lambda kv: -kv[1][0]):
        fv = v["families"].get(name, {})
        note = f" ({fv['note']})" if fv.get("note") else ""
        w(f"| {esc(name)}{esc(note)} | {f[0]:,} | {pct(f[0], n)} | {f[3]:,} | {f[4]:,} | "
          f"{esc(ex_line(f[1][0], 60))} |")
    w("")
    w("Unchecked and unindicated count clues with at least one such node. Op combinations "
      "behind the compound families (clues):")
    w("")
    w("| ops | clues |")
    w("|---|---:|")
    for k, cnt in c.combos.most_common(22):
        w(f"| {k} | {cnt:,} |")
    w("")
    # top table
    w(f"## The {TOP} commonest skeletons (tier 3)")
    w("")
    w("| # | clues | share | skeleton | commonest definitions | verdict | example |")
    w("|---:|---:|---:|---|---|---|---|")
    for i, (sk, r) in enumerate(ranked[:TOP], 1):
        row, _ = judge(sk, v, pats)
        verdict = (row["verdict"] if row else "none")
        defs = ", ".join(f"{k} {pct(x, r[0])}" for k, x in r[4].most_common(2))
        w(f"| {i} | {r[0]:,} | {pct(r[0], n)} | `{esc(sk)}` | {esc(defs)} | {verdict} | "
          f"{esc(ex_line(r[1][0], 55))} |")
    w("")
    # judged rows of the top table, with their why
    notes = [(sk, judge(sk, v, pats)[0]) for sk, _ in ranked[:TOP]]
    notes = [(sk, row) for sk, row in notes if row and row.get("note")]
    if notes:
        w("Notes on the commonest:")
        w("")
        for sk, row in notes:
            w(f"- `{sk}`: {row['note']}")
        w("")
    # pairs
    w("## Which op sits directly under which")
    w("")
    w("Clues containing the pair at least once, parent over child (a charade is an op here). "
      "Pairs that are rare or never occur are the ones to doubt.")
    w("")
    w("| parent | child | clues | example |")
    w("|---|---|---:|---|")
    prs = sorted(c.pairs.items(), key=lambda kv: -kv[1][0])
    for (a, b), (cnt, e) in prs[:45]:
        w(f"| {SHORT.get(a, 'charade')} | {SHORT.get(b, 'charade')} | {cnt:,} | {esc(ex_line(e, 45))} |")
    w("")
    # distributions
    w("## Distributions")
    w("")

    def table(title, counter, label):
        w(f"**{title}**")
        w("")
        w(f"| {label} | clues | share |")
        w("|---:|---:|---:|")
        for k in sorted(counter):
            w(f"| {k} | {counter[k]:,} | {pct(counter[k], n)} |")
        w("")

    table("Tree depth (op nodes, charades included, on the longest path; 0 is no wordplay or a bare leaf)", c.depth, "depth")
    table("Op nesting (named ops only; a charade does not add a level)", c.mdepth, "levels")
    table("Op nodes, charades included", c.nops, "ops")
    table("Non-charade ops (the mechanisms)", c.nncc, "mechanisms")
    cum, marks, hit = 0, {0.5: 0, 0.9: 0, 0.99: 0}, {}
    for i, (_, r) in enumerate(ranked, 1):
        cum += r[0]
        for m in marks:
            if m not in hit and cum >= m * n:
                hit[m] = i
    once = sum(1 for _, r in ranked if r[0] == 1)
    w(f"**Coverage of tier 3.** {hit.get(0.5, '-')} skeletons cover half the clues, {hit.get(0.9, '-')} cover 90%, "
      f"{hit.get(0.99, '-')} cover 99%; {once:,} of the {len(ranked):,} skeletons occur once.")
    w("")
    lt = sum(c.leaves.values())
    w("**Leaf types** (all leaves): " + ", ".join(f"{k} {pct(x, lt)}" for k, x in c.leaves.most_common()) + ".")
    w("")
    dt = collections.Counter()
    for k, x in c.defs.items():
        dt[k] += x
    w("**Definition position** (clues): " + ", ".join(f"`{k}` {pct(x, n)}" for k, x in dt.most_common(8)) + ".")
    w("")
    sers = sorted(c.series, key=lambda s: -c.series[s]["_n"])
    top_f = [k for k, _ in sorted(c.fam.items(), key=lambda kv: -kv[1][0])[:9]]
    w("**Mix by series** (share of the series' annotated clues; most clues first; a column is a family):")
    w("")
    w("| series | clues | " + " | ".join(esc(f) for f in top_f) + " | &lit | mean depth |")
    w("|---|---:|" + "---:|" * (len(top_f) + 2))
    for s in sers:
        sc, tot_s = c.series[s], c.series[s]["_n"]
        if tot_s < 300:
            continue
        al = sum(x for k, x in sc.items() if k.startswith("def:") and k.endswith("&lit"))
        md = sum(d * x for d, x in c.sdepth[s].items()) / tot_s
        w(f"| {s} | {tot_s:,} | " + " | ".join(f"{100 * sc['fam:' + f] / tot_s:.1f}" for f in top_f)
          + f" | {100 * al / tot_s:.1f} | {md:.2f} |")
    w("")
    w(END)
    return "\n".join(out) + "\n"


def write_doc(text):
    DOC.write_text(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dump", metavar="PATH", help="also write every skeleton with its 3 example clues")
    ap.add_argument("--check", action="store_true", help="validate the judgement file and exit")
    ap.add_argument("--limit", type=int, help="read only this many puzzle files (a trial run, not written)")
    a = ap.parse_args(argv)
    v = load_verdicts()
    bad = check_verdicts(v)
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    if a.check:
        return 0
    files = puzzle_paths.puzzle_files()
    c = Census().run(files[:a.limit] if a.limit else files)
    text = build_doc(c, v)
    if a.dump:
        Path(a.dump).write_text(json.dumps({k: {"n": r[0], "examples": r[1], "unindicated": r[2], "unchecked": r[3],
                                                "defs": dict(r[4]), "series": dict(r[5])}
                                            for k, r in c.shapes.items()}))
    if a.limit:
        print(text)
    else:
        write_doc(text)
        print(f"wrote {DOC.relative_to(ROOT)}: {c.n:,} clues, {len(c.shapes):,} skeletons", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
