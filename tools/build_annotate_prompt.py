#!/usr/bin/env python3
"""Write the generated reference section of tools/annotate_prompt.md.

    python3 tools/build_annotate_prompt.py            # rewrite it
    python3 tools/build_annotate_prompt.py --check    # non-zero if stale

The prompt is hand-written prose except for one block between REFERENCE-START and
REFERENCE-END: the wordplay grammar the run writes `wp` in, copied from
tools/wordplay.py's docstring (the parser it must satisfy, so a hand-kept copy
would drift), and worked annotations rendered out of the corpus (EXAMPLES) in
the run's own shape (annotation.to_model of the stored tree; a legacy entry goes
through convert_v2 first), because four runs in five otherwise spent a turn
printing annotations out of a puzzle file to see one. The block is regenerated
on every nightly run and committed with whatever else the run changed. Edit
wordplay.py or the examples, not the prose.

Nothing else belongs in it. A rule a check can see being broken is explained in
that check's own message, where it arrives at the moment it applies; restated
here it is paid for on every turn of every run and still loses to the job in
front of the model.
"""
import json
import sys
from pathlib import Path
import annotation
import convert_v2
import puzzle_schema
import wordplay
from fetch_puzzle import read_puzzle_file, resolve_puzzle
from groups import entry_id

TOOLS = Path(__file__).resolve().parent

PROMPT = TOOLS / "annotate_prompt.md"
START = "<!-- REFERENCE-START — generated by tools/build_annotate_prompt.py -->"
END = "<!-- REFERENCE-END -->"


# Annotations that pass every check with no warning: an anagram inside a
# charade, and a double definition whose notes describe each sense without
# the answer. (The Schema's own `wp` is quiptic-619 5-down, a container.)
EXAMPLES = [("quiptic-619", "11-across"), ("quiptic-619", "10-across")]


def grammar():
    """The Grammar block of wordplay.py's docstring, as it stands."""
    import textwrap
    doc = wordplay.__doc__
    body = doc.split("Grammar\n-------\n", 1)[1].split("\nLegacy trees", 1)[0]
    return textwrap.dedent(body).rstrip("\n").splitlines()


def examples():
    out = ["### Worked annotations", "",
           "Rendered from the corpus in the shape you write; each passes every check.", ""]
    for pid, eid in EXAMPLES:
        puzzle = read_puzzle_file(resolve_puzzle(pid))
        entry = next(e for e in puzzle["entries"] if entry_id(e) == eid)
        ann = entry["annotation"]
        if not puzzle_schema.is_v2_annotation(ann):
            ann, _ = convert_v2.convert(ann, entry, puzzle)
        model = annotation.to_model(ann)
        clue = entry["clue"]
        out += [f"{pid} {eid}, \"{clue['text']}\" ({clue.get('enumeration', '')}), "
                f"solution {entry['solution']}:", "",
                "```json", f"{{\"{eid}\": {{",
                ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}"
                           for k, v in model.items()),
                "}}", "```", ""]
    return out


def section():
    out = [START, "",
           "## Reference",
           "",
           "Generated from tools/wordplay.py, the parser `wp` must satisfy; do not read it to check this.",
           "",
           "### The wordplay grammar",
           "",
           "```"] + grammar() + ["```", ""] + examples() + [END]
    return "\n".join(out) + "\n"


def main(argv):
    text = PROMPT.read_text(encoding="utf-8")
    new = section()
    if START in text and END in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        updated = head + new.rstrip("\n") + tail
    else:
        updated = text.rstrip("\n") + "\n\n" + new
    if updated == text:
        print("annotate_prompt.md: reference section up to date")
        return 0
    if "--check" in argv:
        print("annotate_prompt.md: reference section is stale — the grammar in "
              "wordplay.py or a worked example moved and the prompt still states "
              "the old one. Run: python3 tools/build_annotate_prompt.py", file=sys.stderr)
        return 1
    PROMPT.write_text(updated, encoding="utf-8")
    print(f"annotate_prompt.md: reference section rewritten "
          f"({len(new.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
