#!/usr/bin/env python3
"""Write the generated reference section of tools/annotate_prompt.md.

    python3 tools/build_annotate_prompt.py            # rewrite it
    python3 tools/build_annotate_prompt.py --check    # non-zero if stale

The prompt is hand-written prose except for one block between REFERENCE-START and
REFERENCE-END: the controlled `type` vocabulary, which the run has to choose from
before any check can tell it it chose wrong. It lives in code — `TYPE_PARTS` in validate_annotations.py, `FAMILIES` in app.js
— and a hand-kept copy drifts, so the block is generated from the code on every
nightly run and committed with whatever else the run changed. Edit the tables,
not the prose.

Nothing else belongs in it. A rule a check can see being broken is explained in
that check's own message, where it arrives at the moment it applies; restated
here it is paid for on every turn of every run and still loses to the job in
front of the model.
"""
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import app_tables  # noqa: E402
import validate_annotations as V  # noqa: E402

PROMPT = TOOLS / "annotate_prompt.md"
START = "<!-- REFERENCE-START — generated by tools/build_annotate_prompt.py -->"
END = "<!-- REFERENCE-END -->"


def wrap(items, width=86, indent="  "):
    lines, line = [], indent
    for item in items:
        piece = ("" if line.strip() == "" else " ") + item
        if len(line) + len(piece) > width:
            lines.append(line)
            line = indent + item
        else:
            line += piece
    if line.strip():
        lines.append(line)
    return "\n".join(lines)


def section():
    fams = app_tables.families()
    parts = sorted(V.TYPE_PARTS)
    out = [START, "",
           "## Reference",
           "",
           "Generated from the code that enforces it; do not read app.js or the validator",
           "to check it.",
           "",
           "### The controlled vocabulary for `type`",
           "",
           "Join parts with ` + `. Each part belongs to one family, shown on the",
           "\"What kind of clue is this?\" rung; a compound type's family is the",
           "FIRST row below that matches it.",
           ""]

    claimed = set()
    for label, _blurb, keys in fams:
        mine = sorted(p for p in parts if any(k in p for k in keys))
        claimed |= set(mine)
        out.append(f"**{label}**")
        out.append("")
        out.append(wrap([f"`{p}`" for p in mine] or ["_(no type part matches)_"]))
        out.append("")

    orphans = sorted(set(parts) - claimed)
    if orphans:
        # The smoke test fails on this too; say it here as well, because this is
        # the file the run is reading when it picks a type.
        out.append("**Claimed by no family — do not use until app.js has one:**")
        out.append("")
        out.append(wrap([f"`{p}`" for p in orphans]))
        out.append("")

    out.append(END)
    return "\n".join(out) + "\n"


def main(argv):
    text = PROMPT.read_text(encoding="utf-8")
    new = section()
    if START in text and END in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        updated = head + new.rstrip("\n") + tail
    else:
        updated = text.rstrip("\n") + "\n\n" + new
    if updated == text:
        print("annotate_prompt.md: reference section up to date")
        return 0
    if "--check" in argv:
        print("annotate_prompt.md: reference section is stale — the vocabulary or "
              "the validator's limits moved and the prompt still states the old "
              "ones. Run: python3 tools/build_annotate_prompt.py", file=sys.stderr)
        return 1
    PROMPT.write_text(updated, encoding="utf-8")
    print(f"annotate_prompt.md: reference section rewritten "
          f"({len(new.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
