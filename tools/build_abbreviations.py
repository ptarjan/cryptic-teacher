#!/usr/bin/env python3
"""Publish tools/data/abbreviations.json to the browser as abbreviations.js.

The table was built for tools/clueability.py, which uses it to decide whether a
word can be assembled at all. It is just as useful to a solver, and for the
opposite reason: a charade is our commonest clue type, and the hard part is not
recognising one, it is knowing that "sailor" is AB because the convention says
so and no amount of staring will derive it. The blocks rung now says which
pieces were conventions.

Generated, not hand-written, so the solver's glossary and the clue-writer's
cannot drift into two different tables. tools/smoke_test.js fails if this file
is stale.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "data" / "abbreviations.json"
# Clue word -> {letters: clues}, off the solving blogs and our own annotations
# (tools/letter_facts.py --lexicons). Read only by seen(), for the page.
LEXICON = ROOT / "tools" / "data" / "lexicons" / "blocks.json"
# seen() keeps a reading only when this many clues use it.
SEEN_MIN = 10
# Two-letter readings that are everyday words. POPULAR -> IN and WHEN -> AS are
# synonyms, however often setters use them, not conventions to learn.
EVERYDAY = frozenset("AM AN AS AT BE BY DO GO HE HI IF IN IS IT ME MY NO OF OH OK "
                     "ON OR OX SO TO UP US WE".split())
OUT = ROOT / "abbreviations.js"
# Where the glossary belongs inside the lesson. The 400 rows themselves live on
# one URL — /abbreviations/ — so what tools/build_seo_pages.py writes between
# these markers is the pointer to it.
MARK_START = "<!-- ABBREVIATIONS-START -->"
MARK_END = "<!-- ABBREVIATIONS-END -->"
COLUMNS = 3


def render():
    table = json.loads(SRC.read_text())["abbreviations"]
    # Sorted so the output is a function of the input alone and a no-op rebuild
    # produces no diff.
    body = json.dumps(dict(sorted(table.items())), indent=1, sort_keys=True)
    return (
        "// GENERATED by tools/build_abbreviations.py from\n"
        "// tools/data/abbreviations.json. Do not edit: edit the JSON and rerun.\n"
        "//\n"
        "// Letters -> the clue words that stand for them. Read by app.js to name\n"
        "// the pieces of a charade that a solver was meant to know rather than work\n"
        "// out.\n"
        f"const ABBREVIATIONS = {body};\n"
    )


def anchor(word):
    """The id app.js links a named convention to. Shared by both consumers."""
    return "abbr-" + re.sub(r"[^a-z0-9]+", "-", word.lower()).strip("-")


def by_word():
    """The table inverted: clue word -> every set of letters it can stand for."""
    senses = {}
    for letters, words in json.loads(SRC.read_text())["abbreviations"].items():
        for w in words:
            senses.setdefault(w, []).append(letters)
    if len({anchor(w) for w in senses}) != len(senses):
        raise SystemExit(
            "two senses in tools/data/abbreviations.json slugify to the same anchor; "
            "one of them would be unreachable from a hint")
    return senses


def subsequence(short, word):
    """Whether short's letters appear in word in order (T in TRADE, TY in TOTALLY)."""
    rest = iter(word)
    return all(c in rest for c in short)


def seen():
    """The conventions the corpus uses that the curated table lacks, as sorted
    (clue word, letters, clues) rows.

    blocks.json holds every reading a clue piece was given, synonyms and fodder
    included, so a reading is kept only when it is a convention by construction:
    one or two letters, not an everyday word, used by at least SEEN_MIN clues,
    and not made of the clue word's own letters in order. That last rule costs
    the initial-letter conventions (R for river), which the curated table
    already has, and is what keeps out the clues that took a word's first or
    outer letters: T from trade, TY from totally.

    This is for the page only. tools/clueability.py builds from
    tools/data/abbreviations.json alone, so nothing here widens what it may use.
    """
    curated = {(letters_of(w), k) for k, ws in json.loads(SRC.read_text())["abbreviations"].items()
               for w in ws}
    rows = []
    for word, readings in json.loads(LEXICON.read_text()).items():
        bare = letters_of(word)
        for letters, n in readings.items():
            if (n >= SEEN_MIN and len(letters) <= 2 and len(letters) < len(bare)
                    and letters not in EVERYDAY and not subsequence(letters, bare)
                    and (bare, letters) not in curated):
                rows.append((word.lower(), letters, n))
    return sorted(rows)


def letters_of(s):
    """A clue word or reading reduced to the capitals blocks.json keys on."""
    return re.sub(r"[^A-Z0-9]", "", (s or "").upper())


def table_html(senses, links=None, rare=None):
    """The glossary markup, for the one page that carries it: /abbreviations/.

    The data is stored letters-first because that is the direction the assembler
    works in, and it is the wrong direction for a person: a solver arrives at
    this table holding a word ("check") and wanting the letters. So it is
    inverted, and generated rather than hand-picked, because a curated "starter
    set" is a second table that drifts from the one the hints teach from — which
    is how the site could tell a solver CH was check while the glossary had
    never heard of it.

    Every word cell carries its own id. A hint that names a convention links to
    that one row, so the solver lands on the line they asked about instead of on
    the top of a four-hundred-row table with the reading still to do.

    `links` maps a word to a clue that uses it. `rare` maps a word to seen()'s
    readings for it, which join the same row in muted type: one list, looked up
    the same way, with the curated readings first.
    """
    links, rare = links or {}, rare or {}
    by_anchor = {anchor(w): w for w in senses}
    for w in rare:
        by_anchor.setdefault(anchor(w), w)
    merged = {}
    for w, r in rare.items():
        merged.setdefault(by_anchor[anchor(w)], []).extend(r)
    rare = merged
    rows, cells = [], sorted(by_anchor.values(), key=str.lower)
    for i in range(0, len(cells), COLUMNS):
        row = "".join(
            f'<td id="{anchor(w)}">'
            + (f'<a href="{links[w]}">{w}</a>' if w in links else w)
            + "</td><td>" + ", ".join(
                sorted(senses.get(w, []))
                + [f'<span class="muted" title="seen in {n:,} clues">{k}</span>'
                   for k, n in rare.get(w, [])]) + "</td>"
            for w in cells[i:i + COLUMNS])
        rows.append(f"<tr>{row}</tr>")
    return '<table class="glossary">\n' + "\n".join(rows) + "\n</table>"


def write(path, text):
    stale = not path.exists() or path.read_text(encoding="utf-8") != text
    if stale:
        path.write_text(text, encoding="utf-8")
    return "rebuilt" if stale else "unchanged"


if __name__ == "__main__":
    print(f"abbreviations.js: {write(OUT, render())}")
