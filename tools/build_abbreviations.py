"""The abbreviations table, and its publication to the browser as abbreviations.js.

The table was built for tools/clueability.py, which uses it to decide whether a
word can be assembled at all. It is just as useful to a solver, and for the
opposite reason: a charade is our commonest clue type, and the hard part is not
recognising one, it is knowing that "sailor" is AB because the convention says
so and no amount of staring will derive it. The blocks rung now says which
pieces were conventions.

table() is the one table every reader uses: the senses curated in
tools/data/abbreviations.json, the members of FAMILIES, and every reading
SEEN_MIN or more clues in tools/data/lexicons/blocks.json use, unless derived()
shows it is pieces the table holds or REJECT says why it is not one convention.
Only the curated part is committed; the rest follows the corpus.

    python3 tools/build_abbreviations.py

writes table() to abbreviations.js, so the solver's glossary and the
clue-writer's cannot drift into two different tables.
"""
