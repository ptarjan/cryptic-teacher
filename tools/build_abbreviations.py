def families():
    """FAMILIES as [(name, [(word, letters)])]."""
    return [(name, [tuple(m.strip().rsplit(" ", 1)) for m in spec.split(",")])
            for name, spec in FAMILIES]


def curated():
    """SRC's letters -> senses: what the corpus cannot show, written by hand or
    by tools/add_abbreviation.py."""
    return json.loads(SRC.read_text(encoding="utf-8"))["abbreviations"]


def table():
    """Letters -> sorted clue words: curated(), FAMILIES and the conventions
    the corpus uses (candidates() that derived() does not explain). A reading
    the curated part already spells, punctuation aside, keeps that spelling:
    blocks.json drops hyphens and apostrophes."""
    global _TABLE
    if _TABLE is None:
        out = {k: set(ws) for k, ws in curated().items()}
        for _, members in families():
            for w, k in members:
                out.setdefault(k, set()).add(w)
        spelled = {letters_of(w): w for ws in out.values() for w in sorted(ws)}
        have = {(letters_of(w), k) for k, ws in out.items() for w in ws}
        rows = candidates()
        known = have | {(letters_of(w), k) for w, k, _ in rows}
        for w, k, _ in rows:
            if (letters_of(w), k) not in have and not derived(w, k, known):
                out.setdefault(k, set()).add(spelled.setdefault(letters_of(w), w))
                have.add((letters_of(w), k))
        _TABLE = {k: sorted(out[k]) for k in sorted(out)}
    return _TABLE


_TABLE = None


def usage():
    """LEXICON as {(letters_of(clue word), letters): clues}, spellings merged."""
    global _USAGE
    if _USAGE is None:
        _USAGE = {}
        for word, readings in json.loads(LEXICON.read_text()).items():
            for k, n in readings.items():
                key = (letters_of(word), k)
                _USAGE[key] = _USAGE.get(key, 0) + n
    return _USAGE


_USAGE = None


def clues(word, letters):
    """How many clues read word as letters, 0 for none."""
    return usage().get((letters_of(word), letters), 0)


def count_html(n):
    """A clue count beside a reading, as /learn/ shows one beside an indicator."""
    return f'&nbsp;<span class="muted n">{n:,}</span>' if n else ""


def ranked(pairs):
    """(word, letters) pairs most used first; unused ones keep their order, last."""
    return sorted(pairs, key=lambda p: -clues(*p))


def common_html(senses, n=40):
    """The n readings the table holds that most clues use, each with its count."""
    top = ranked(sorted((w, k) for w, ks in senses.items() for k in ks))[:n]
    return '<p class="glossary-common">' + ", ".join(
        f'<a href="#{anchor(w)}">{w}</a> <strong>{k}</strong>{count_html(clues(w, k))}'
        for w, k in top) + "</p>"


def families_html():
    """families() as one line each, the family most clues use first and its
    members likewise, every word linked to its A-to-Z entry."""
    fams = sorted(((sum(clues(*m) for m in members), name, ranked(members))
                   for name, members in families()), key=lambda f: -f[0])
    return '<dl class="glossary-families">\n' + "\n".join(
        f"<div><dt>{name}{count_html(total)}</dt><dd>" + " &middot; ".join(
            f'<a href="#{anchor(w)}">{w}</a> <strong>{k}</strong>{count_html(clues(w, k))}'
            for w, k in members)
        + "</dd></div>" for total, name, members in fams) + "\n</dl>"


def anchor(word):
    """The id app.js links a named convention to. Shared by both consumers."""
    return "abbr-" + re.sub(r"[^a-z0-9]+", "-", word.lower()).strip("-")


def by_word():
    """The table inverted: clue word -> every set of letters it can stand for."""
    senses = {}
    for letters, words in table().items():
        for w in words:
            senses.setdefault(w, []).append(letters)
    if len({anchor(w) for w in senses}) != len(senses):
        raise SystemExit(
            "two senses in table() slugify to the same anchor; "
            "one of them would be unreachable from a hint")
    return senses


def subsequence(short, word):
    """Whether short's letters appear in word in order (T in TRADE, TY in TOTALLY)."""
    rest = iter(word)
    return all(c in rest for c in short)


def candidates():
    """The readings in LEXICON that look like conventions, as sorted
    (clue word, letters, clues) rows.

    blocks.json holds every reading a clue piece was given, synonyms and fodder
    included, so a reading is kept only when it is a convention by construction:
    one or two letters, not an everyday word, used by at least SEEN_MIN clues,
    not made of the clue word's own letters in order, and not in REJECT. The
    letters rule costs the initial-letter conventions (R for river), which the
    curated table has, and is what keeps out the clues that took a word's first
    or outer letters: T from trade, TY from totally.
    """
    rows = []
    for word, readings in json.loads(LEXICON.read_text()).items():
        bare = letters_of(word)
        for letters, n in readings.items():
            if (n >= SEEN_MIN and len(letters) <= 2 and len(letters) < len(bare)
                    and letters not in EVERYDAY and not subsequence(letters, bare)
                    and (word.lower(), letters) not in REJECT):
                rows.append((word.lower(), letters, n))
    return sorted(rows)


def derived(word, letters, known):
    """Why a reading is pieces the table already holds rather than a convention
    of its own, or None. `known` is (letters_of(word), letters) pairs.

    An article on a sense (a hundred C, a king AR), a plural or pair written
    twice (lines LL, two females FF), and a self-reference with 's or 'd
    (setter's IM, one had ID) each teach nothing the parts do not.
    """
    if letters == "IM" and (word.endswith("s") or word.endswith(" is")):
        return "I + 'm, the I being the clue's self-reference"
    if letters == "ID" and word.endswith(" had") and (letters_of(word[:-4]), "I") in known:
        return f"{word[:-4]} = I, + 'd for had"
    for head in ("a ", "an ", "the ", "one "):
        if word.startswith(head):
            rest = letters_of(word[len(head):])
            if (rest, letters) in known:
                return f"{word[len(head):]} = {letters}, with {head.strip()!r}"
            if head == "a " and letters[0] == "A" and (rest, letters[1:]) in known:
                return f"A + {word[len(head):]} = {letters[1:]}"
    if len(letters) == 2 and letters[0] == letters[1]:
        bare = word.removeprefix("two ").removeprefix("both ")
        stems = {bare, bare.removesuffix("s"), bare.removesuffix("es")}
        if bare.endswith("ies"):
            stems.add(bare[:-3] + "y")
        for stem in sorted(stems, key=len):
            if (letters_of(stem), letters[0]) in known:
                return f"{stem} = {letters[0]}, twice"
    return None


def readings():
    """candidates() table() leaves out, as (clue word, letters, clues, why),
    `why` being derived()'s reason."""
    have = {(letters_of(w), k) for k, ws in table().items() for w in ws}
    rows = candidates()
    known = have | {(letters_of(w), k) for w, k, _ in rows}
    return [(w, k, n, derived(w, k, known)) for w, k, n in rows
            if (letters_of(w), k) not in have]


def letters_of(s):
    """A clue word or reading reduced to the capitals blocks.json keys on."""
    return re.sub(r"[^A-Z0-9]", "", (s or "").upper())


def table_html(senses, links=None, rare=None):
    """The glossary markup, for the one page that carries it: /abbreviations/.

    The data is stored letters-first because that is the direction the assembler
    works in, and it is the wrong direction for a person: a solver arrives at
    this table holding a word ("check") and wanting the letters. So it is
    inverted, and generated rather than hand-picked, because a curated "starter
    set" is a second table that drifts from the one the hints teach from — which
    is how the site could tell a solver CH was check while the glossary had
    never heard of it.

    Grouped A to Z, each group a word list flowed into as many columns as the
    screen fits. Every entry carries its own id. A hint that names a convention links to
    that one row, so the solver lands on the line they asked about instead of on
    the top of a four-hundred-row table with the reading still to do.

    `links` maps a word to a clue that uses it. `rare` maps a word to its
    readings() as (letters, clues, why), which join the same row in muted type:
    one list, looked up the same way. A row's readings run most used first,
    each with how many clues use it.
    """
    links, rare = links or {}, rare or {}
    by_anchor = {anchor(w): w for w in senses}
    for w in rare:
        by_anchor.setdefault(anchor(w), w)
    merged = {}
    for w, r in rare.items():
        merged.setdefault(by_anchor[anchor(w)], []).extend(r)
    rare = merged
    groups = {}
    for w in sorted(by_anchor.values(), key=str.lower):
        head = w[0].upper() if w[0].isalpha() else "0–9"
        groups.setdefault(head, []).append(w)
    out = ['<p class="glossary-jump">' + " ".join(
        f'<a href="#abbr-{h[0].lower()}-">{h}</a>' for h in groups) + "</p>"]
    for head, words in groups.items():
        out.append(f'<h3 id="abbr-{head[0].lower()}-">{head}</h3>\n<dl class="glossary">')
        for w in words:
            letters = [(clues(w, k), k, k) for k in senses.get(w, [])] + [
                (n, k, f'<span class="muted"{f' title="{escape(why)}"' if why else ""}>{k}</span>') for k, n, why in rare.get(w, [])]
            letters.sort(key=lambda r: (-r[0], r[1]))
            word = f'<a href="{links[w]}">{w}</a>' if w in links else w
            out.append(f'<div id="{anchor(w)}"><dt>{word}</dt><dd>' + " &middot; ".join(
                html + count_html(n) for n, _, html in letters) + "</dd></div>")
        out.append("</dl>")
    return "\n".join(out)


def write(path, text):
    stale = not path.exists() or path.read_text(encoding="utf-8") != text
    if stale:
        path.write_text(text, encoding="utf-8")
    return "rebuilt" if stale else "unchanged"


if __name__ == "__main__":
    print(f"abbreviations.js: {write(OUT, render())}")
