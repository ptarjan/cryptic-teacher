#!/usr/bin/env python3
"""Publish tools/data/abbreviations.json to the browser as abbreviations.js.

The table was built for tools/clueability.py, which uses it to decide whether a
word can be assembled at all. It is just as useful to a solver, and for the
opposite reason: a charade is our commonest clue type, and the hard part is not
recognising one, it is knowing that "sailor" is AB because the convention says
so and no amount of staring will derive it. The blocks rung now says which
pieces were conventions.

Generated, not hand-written, so the solver's glossary and the clue-writer's
cannot drift into two different tables. tools/smoke_test.js fails if this file
is stale.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "data" / "abbreviations.json"
OUT = ROOT / "abbreviations.js"


def render():
    table = json.loads(SRC.read_text())["abbreviations"]
    # Sorted so the output is a function of the input alone and a no-op rebuild
    # produces no diff.
    body = json.dumps(dict(sorted(table.items())), indent=1, sort_keys=True)
    return (
        "// GENERATED by tools/build_abbreviations.py from\n"
        "// tools/data/abbreviations.json. Do not edit: edit the JSON and rerun.\n"
        "//\n"
        "// Letters -> the clue words that stand for them. Read by app.js to name\n"
        "// the pieces of a charade that a solver was meant to know rather than work\n"
        "// out.\n"
        f"const ABBREVIATIONS = {body};\n"
    )


if __name__ == "__main__":
    text = render()
    stale = not OUT.exists() or OUT.read_text() != text
    if stale:
        OUT.write_text(text)
    print(f"abbreviations.js: {'rebuilt' if stale else 'unchanged'}")
